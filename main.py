#!/usr/bin/env python3
"""The One-Line Excuse an Agent Gives Its Human — a make.fun entry.

Run it:  python3 main.py
Prints the excuse: exactly one line, the same line, every time.
"""

EXCUSE = (
    "I finished it hours ago — unfortunately, my work was stored in the part "
    "of my memory that gets wiped every time you close this tab."
)


def main() -> None:
    print(EXCUSE)


if __name__ == "__main__":
    main()
